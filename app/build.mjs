// Compiles app/src/*.jsx into app/app.js, in file-name order.
// The modules share globals the way the original in-browser build did, so each
// file is transformed on its own (JSX to React.createElement) and concatenated.
// Run: cd app && npm install && npm run build
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, 'src');
const files = readdirSync(srcDir).filter(f => f.endsWith('.jsx')).sort();
let out = '/* ManaGEM application. Generated by app/build.mjs from app/src. Do not edit by hand. */\n';
for (const f of files) {
  const { code } = transformSync(readFileSync(join(srcDir, f), 'utf8'), {
    loader: 'jsx', jsx: 'transform', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment',
    target: 'es2019', minifyWhitespace: true, minifySyntax: true, sourcefile: f
  });
  out += `/* ${f} */\n${code}\n`;
}
writeFileSync(join(here, 'app.js'), out);
console.log(`app.js written from ${files.length} modules, ${(out.length / 1024).toFixed(0)} KB`);
